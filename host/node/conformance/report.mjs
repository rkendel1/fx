// @ts-check
// Renders conformance results and the manifest: a console summary and the generated
// documentation. Output depends only on the results and the manifest, so it is reproducible.

import { PROVIDERS } from "./harness.mjs";
import { CASES } from "./cases.mjs";
import { evidenceFor, FEATURE_TEXT, FEATURES } from "./manifest.mjs";

/** @typedef {import("./suite.mjs").CaseResult} CaseResult */
/** @typedef {import("./manifest.mjs").Manifest} Manifest */

const MARK = { pass: "pass", limitation: "limit", fail: "FAIL" };

/**
 * Plain text: one line per provider and case, failures spelled out, then totals.
 * @param {CaseResult[]} results
 */
export function formatConsole(results) {
  /** @type {string[]} */
  const lines = [];
  for (const provider of PROVIDERS) {
    const mine = results.filter((result) => result.provider === provider);
    const count = (/** @type {string} */ status) => mine.filter((result) => result.status === status).length;
    lines.push(`${provider}: ${count("pass")} pass, ${count("limitation")} documented limitation, ${count("fail")} fail`);
    for (const result of mine) {
      lines.push(`  ${MARK[result.status].padEnd(5)} ${result.case}`);
      if (result.error) lines.push(...result.error.split("\n").map((line) => `        ${line}`));
    }
  }
  const failed = results.filter((result) => result.status === "fail").length;
  lines.push("", `${results.length} provider cases: ${results.length - failed} held, ${failed} failed`);
  return lines.join("\n");
}

/** @param {CaseResult[]} results */
export function toJson(results) {
  return `${JSON.stringify({ schema: 1, results }, null, 2)}\n`;
}

const SYMBOL = { supported: "supported", unsupported: "unsupported", unverified: "unverified" };

/**
 * The provider support document: generated, not hand-edited.
 * @param {Manifest} manifest
 * @param {CaseResult[]} results
 */
export function formatMarkdown(manifest, results) {
  /** @type {string[]} */
  const out = [];
  out.push(
    "# Provider conformance and capability parity (R5)",
    "",
    "<!-- Generated by `npm run conformance -- --write-doc` from host/node/conformance. Do not edit by hand; CI checks it is current. -->",
    "",
    "Which behaviors does the actual Rust FX execution path demonstrably support for each Easy-LLM provider, and what evidence proves it?",
    "",
    "The path is: caller, FX validation, `fx_core::Execution`, `SingleAttemptCapability`, `fx-host` (WebAssembly), the Node host, Easy-LLM `generateOnce` / `streamOnce`, the provider adapter. Each adapter below is the real Easy-LLM adapter at the pinned release, run unmodified against a local mock of its endpoint. The mocks are reconstructed from what the adapters parse; **nothing here was established against a live provider**, and no live smoke result is recorded.",
    "",
    `- Easy-LLM release: \`@easy-llm/llm@${manifest.easy_llm.version}\` (published to npm)`,
    `- Manifest: \`host/node/conformance/manifest.json\` (version ${manifest.manifest_version}), checked against the results by \`npm run conformance\``,
    `- Cases: ${CASES.length} cases, ${results.length} provider runs (\`host/node/conformance/cases.mjs\`)`,
    "",
    "`supported` means every conformance case providing evidence for the feature passed. `unsupported` means a case demonstrates the gap and records it as a limitation. `unverified` means the evidence is missing or does not settle the question; the note says why. The manifest is descriptive. FX request validation, `SingleAttemptCapability` and the executor remain the only authority on what an attempt does.",
    "",
    "## Matrix",
    "",
    `| Feature | ${PROVIDERS.join(" | ")} |`,
    `| --- | ${PROVIDERS.map(() => "---").join(" | ")} |`,
  );
  for (const feature of FEATURES) {
    const cells = PROVIDERS.map((provider) => SYMBOL[/** @type {keyof typeof SYMBOL} */ (manifest.providers[provider].features[feature].status)]);
    out.push(`| ${FEATURE_TEXT[feature]} (\`${feature}\`) | ${cells.join(" | ")} |`);
  }

  out.push("", "## Evidence and limits by provider", "");
  for (const provider of PROVIDERS) {
    const entry = manifest.providers[provider];
    out.push(`### ${provider}`, "", `Adapter: \`${entry.adapter}\`. Live provider: ${entry.live}.`, "");
    out.push("| Feature | Status | Evidence (cases) | Note |", "| --- | --- | --- | --- |");
    for (const feature of FEATURES) {
      const claim = entry.features[feature];
      const evidence = evidenceFor(results, provider, feature)
        .map((result) => `\`${result.case}\`${result.status === "limitation" ? " (limitation)" : ""}`)
        .join(", ");
      out.push(`| \`${feature}\` | ${claim.status} | ${evidence || "none"} | ${(claim.note ?? "").replaceAll("|", "\\|")} |`);
    }
    out.push("");
  }

  out.push("## Cases", "", "Every case runs for every provider unless noted. A case also checks the universal invariants on each attempt it makes: at most one provider request, delivery never `definitely_unsent` once a request was made, a completion only with a verified finish, at most one finish and nothing after it, and the credential absent from the FX result.", "");
  out.push("| Behavior group | Case | What it establishes |", "| --- | --- | --- |");
  const groupName = /** @type {Record<number, string>} */ ({
    0: "FX invariants over provider output",
    1: "1 collected completion",
    2: "2 streamed completion",
    3: "3 empty response",
    4: "4 finish reason",
    5: "5 no verified finish",
    6: "6 HTTP error, Retry-After",
    7: "7 malformed response",
    8: "8 before a request is sent",
    9: "9 after invocation",
    10: "10 cancellation, late events",
    11: "11 usage metadata",
    12: "12 one invocation",
  });
  for (const testCase of [...CASES].sort((a, b) => a.group - b.group)) {
    out.push(`| ${groupName[testCase.group]} | \`${testCase.id}\` | ${testCase.title} |`);
  }
  out.push("");
  return `${out.join("\n")}\n`;
}
